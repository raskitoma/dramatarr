'use strict';

/**
 * yt-dlp download backend — the same engine MeTube wraps.
 *
 * The native downloader in src/downloader.js handles the common cases, but these
 * sites rotate CDNs and playlist shapes constantly. yt-dlp already knows the
 * awkward variants (odd master playlists, byte-range fMP4, throttled hosts), so
 * it makes a good second attempt.
 *
 * It is given the *same* solved-session identity as the native path: cookies,
 * User-Agent and Referer. Without those these CDNs return 403.
 */

const fs = require('fs');
const fsp = require('fs/promises');
const os = require('os');
const path = require('path');
const { spawn, spawnSync } = require('child_process');

const { cookieHeaderFor } = require('./net');

/**
 * @returns {boolean}
 */
function isYtDlpAvailable() {
  const probe = process.platform === 'win32' ? 'where' : 'which';
  return spawnSync(probe, ['yt-dlp'], { stdio: 'ignore' }).status === 0;
}

const HAS_YTDLP = isYtDlpAvailable();

/**
 * Writes a Netscape cookie jar for the target URL.
 *
 * yt-dlp takes cookies as a file, not a header, and it re-requests segments
 * itself, so the jar has to cover the media host too.
 *
 * @param {string} filePath
 * @param {Array} cookies
 * @returns {Promise<boolean>} whether anything was written
 */
async function writeCookieJar(filePath, cookies) {
  if (!Array.isArray(cookies) || cookies.length === 0) return false;

  const lines = ['# Netscape HTTP Cookie File', '# Generated by DramaDown'];
  const farFuture = 2147483647;

  for (const cookie of cookies) {
    if (!cookie || !cookie.name) continue;
    const domain = String(cookie.domain || '');
    if (!domain) continue;
    // Leading dot means "include subdomains" in this format.
    const includeSubdomains = domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const expires = Number.isFinite(cookie.expires) && cookie.expires > 0 ? Math.floor(cookie.expires) : farFuture;
    lines.push(
      [
        domain,
        includeSubdomains,
        cookie.path || '/',
        cookie.secure ? 'TRUE' : 'FALSE',
        expires,
        cookie.name,
        cookie.value
      ].join('\t')
    );
  }

  if (lines.length <= 2) return false;
  await fsp.writeFile(filePath, lines.join('\n') + '\n', 'utf8');
  return true;
}

/**
 * Downloads one video with yt-dlp.
 *
 * @param {string} uri
 * @param {string} outputPath - Destination .mp4
 * @param {object} [options] - { context, onEpisodeProgress, signal, concurrentFragments }
 * @returns {Promise<{bytes: number, backend: string}>}
 */
async function downloadWithYtDlp(uri, outputPath, options = {}) {
  const { context = {}, onEpisodeProgress = () => {}, signal, concurrentFragments = 6 } = options;

  if (!HAS_YTDLP) throw new Error('yt-dlp is not installed.');

  const workDir = await fsp.mkdtemp(path.join(os.tmpdir(), 'dramadown-ytdlp-'));
  const cookieFile = path.join(workDir, 'cookies.txt');

  try {
    const hasCookies = await writeCookieJar(cookieFile, context.cookies);

    const args = [
      '--no-warnings',
      '--no-playlist',
      // Deliberately NOT --no-part. Writing straight to the final filename
      // leaves a truncated but playable file behind when a run dies, which then
      // looks like a completed episode. With .part files yt-dlp only renames on
      // success, and --continue resumes the leftover instead of restarting.
      '--continue',
      '--no-mtime',
      '--retries', '5',
      '--fragment-retries', '10',
      '--socket-timeout', '60',
      '--concurrent-fragments', String(concurrentFragments),
      // Prefer the tallest stream, then merge into mp4.
      '--format', 'bestvideo*+bestaudio/best',
      '--merge-output-format', 'mp4',
      // Machine-readable progress on stdout.
      '--newline',
      '--progress',
      '--progress-template', 'DDPROGRESS %(progress._percent_str)s %(progress.downloaded_bytes)s %(progress.total_bytes)s',
      '--output', outputPath,
      '--paths', `temp:${workDir}`
    ];

    if (context.userAgent) args.push('--user-agent', context.userAgent);
    if (context.referer) args.push('--referer', context.referer);
    if (hasCookies) args.push('--cookies', cookieFile);

    // Some of these hosts also gate on a cookie header for the media domain.
    const cookieHeader = cookieHeaderFor(uri, context.cookies);
    if (cookieHeader && !hasCookies) args.push('--add-header', `Cookie:${cookieHeader}`);

    args.push(uri);

    try {
      await runYtDlp(args, { signal, onEpisodeProgress });
    } catch (err) {
      // A failed run must not leave anything at the final path that a later
      // pass would mistake for a finished episode.
      await discardPartialOutput(outputPath);
      throw err;
    }

    const stat = await fsp.stat(outputPath).catch(() => null);
    if (!stat || stat.size === 0) {
      await discardPartialOutput(outputPath);
      throw new Error('yt-dlp produced no output file.');
    }

    await removeStrayFragments(outputPath);
    return { bytes: stat.size, backend: 'yt-dlp' };
  } finally {
    await fsp.rm(workDir, { recursive: true, force: true }).catch(() => {});
  }
}

/**
 * Removes anything a dead yt-dlp run left at or beside the output path.
 * @param {string} outputPath
 */
async function discardPartialOutput(outputPath) {
  await fsp.rm(outputPath, { force: true }).catch(() => {});
  await fsp.rm(`${outputPath}.part`, { force: true }).catch(() => {});
  await removeStrayFragments(outputPath);
}

/**
 * Clears `<file>-FragN` / `<file>.partN` scraps from fragmented downloads.
 * @param {string} outputPath
 */
async function removeStrayFragments(outputPath) {
  const dir = path.dirname(outputPath);
  const base = path.basename(outputPath);
  const names = await fsp.readdir(dir).catch(() => []);

  for (const name of names) {
    if (name === base) continue;
    if (name.startsWith(`${base}-Frag`) || /^.+\.part\d+$/.test(name) && name.startsWith(base)) {
      await fsp.rm(path.join(dir, name), { force: true }).catch(() => {});
    }
  }
}

/**
 * @param {string[]} args
 * @param {{signal?: AbortSignal, onEpisodeProgress: function}} options
 * @returns {Promise<void>}
 */
function runYtDlp(args, options) {
  const { signal, onEpisodeProgress } = options;

  return new Promise((resolve, reject) => {
    const child = spawn('yt-dlp', args, { stdio: ['ignore', 'pipe', 'pipe'] });
    let stderr = '';
    let stdoutTail = '';

    const onAbort = () => child.kill('SIGKILL');
    signal?.addEventListener('abort', onAbort, { once: true });

    child.stdout.on('data', chunk => {
      const text = chunk.toString();
      stdoutTail = (stdoutTail + text).slice(-500);

      for (const line of text.split('\n')) {
        const match = line.match(/^DDPROGRESS\s+([\d.]+)%\s+(\d+|NA)\s+(\d+|NA)/);
        if (!match) continue;
        const bytes = match[2] === 'NA' ? 0 : Number(match[2]);
        const totalBytes = match[3] === 'NA' ? 0 : Number(match[3]);
        onEpisodeProgress({
          downloadedSegments: 0,
          totalSegments: 0,
          bytes,
          totalBytes,
          percentage: Math.round(Number(match[1]))
        });
      }
    });

    child.stderr.on('data', chunk => {
      stderr = (stderr + chunk.toString()).slice(-2000);
    });

    child.on('error', err => {
      signal?.removeEventListener('abort', onAbort);
      reject(new Error(`yt-dlp could not be started: ${err.message}`));
    });

    child.on('close', code => {
      signal?.removeEventListener('abort', onAbort);
      if (code === 0) return resolve();
      if (signal?.aborted) return reject(new Error('Cancelled.'));
      const detail = (stderr || stdoutTail).trim().split('\n').filter(Boolean).pop() || `exit code ${code}`;
      reject(new Error(`yt-dlp failed: ${detail}`));
    });
  });
}

module.exports = { HAS_YTDLP, downloadWithYtDlp, writeCookieJar };
